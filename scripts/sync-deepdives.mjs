/**
 * Regenerate the deep-dive wiring from whatever is present in
 * `src/data/deepdives/concepts/`.
 *
 * Deep dives are authored one file per concept so they can be written in parallel
 * without collisions. This script derives the per-sphere barrels and the
 * availability registry from those files, so the wiring can never drift from the
 * content. Run it after adding or removing a concept file:
 *
 *   node scripts/sync-deepdives.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// fileURLToPath, not URL.pathname — the project path contains spaces, which
// pathname leaves percent-encoded.
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DATA_DIR = join(ROOT, 'src', 'data');
const DEEP_DIVE_DIR = join(DATA_DIR, 'deepdives');
const CONCEPTS_DIR = join(DEEP_DIVE_DIR, 'concepts');

const SPHERES = [
  { n: 1, id: 'internal-architecture', constName: 'SPHERE_1_DEEP_DIVES' },
  { n: 2, id: 'social-dynamics', constName: 'SPHERE_2_DEEP_DIVES' },
  { n: 3, id: 'strategic-interactions', constName: 'SPHERE_3_DEEP_DIVES' },
  { n: 4, id: 'behavioral-economics', constName: 'SPHERE_4_DEEP_DIVES' },
];

/** Concept id -> sphere number, read straight from the curriculum source files. */
function buildConceptIndex() {
  const index = new Map();
  for (const sphere of SPHERES) {
    const src = readFileSync(join(DATA_DIR, `sphere${sphere.n}.ts`), 'utf8');
    for (const match of src.matchAll(/^ {4}id: '([^']+)'/gm)) {
      index.set(match[1], sphere.n);
    }
  }
  return index;
}

const toCamel = (kebab) => kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const conceptIndex = buildConceptIndex();

const files = readdirSync(CONCEPTS_DIR)
  .filter((f) => f.endsWith('.ts'))
  .map((f) => f.replace(/\.ts$/, ''))
  .sort();

const unknown = files.filter((id) => !conceptIndex.has(id));
if (unknown.length > 0) {
  console.error(`These deep-dive files do not match any concept id:\n  ${unknown.join('\n  ')}`);
  process.exit(1);
}

const bySphere = new Map(SPHERES.map((s) => [s.n, []]));
for (const id of files) bySphere.get(conceptIndex.get(id)).push(id);

// --- per-sphere barrels ---------------------------------------------------
for (const sphere of SPHERES) {
  const ids = bySphere.get(sphere.n);
  const imports = ids
    .map((id) => `import { deepDive as ${toCamel(id)} } from './concepts/${id}';`)
    .join('\n');
  const entries = ids.map((id) => `  '${id}': ${toCamel(id)},`).join('\n');

  const out = `import type { DeepDive } from '../../types/curriculum';
${imports ? `${imports}\n` : ''}
/**
 * Long-form deep dives for Sphere ${sphere.n}, keyed by concept id.
 * Code-split — loaded on demand by \`src/data/deepdives/index.ts\`.
 *
 * GENERATED by \`scripts/sync-deepdives.mjs\` — do not edit by hand.
 * Add a file under \`./concepts/\` and re-run the script instead.
 */
export const ${sphere.constName}: Record<string, DeepDive> = {${entries ? `\n${entries}\n` : ''}};
`;

  writeFileSync(join(DEEP_DIVE_DIR, `sphere${sphere.n}.ts`), out);
}

// --- availability registry ------------------------------------------------
const registry = `/**
 * Concepts that have a written deep dive.
 *
 * Kept as a plain list so the UI can decide whether to offer a read without first
 * downloading a large code-split chunk.
 *
 * GENERATED by \`scripts/sync-deepdives.mjs\` — do not edit by hand.
 */
export const CONCEPTS_WITH_DEEP_DIVE: ReadonlySet<string> = new Set([
${files.map((id) => `  '${id}',`).join('\n')}
]);
`;

writeFileSync(join(DEEP_DIVE_DIR, 'registry.ts'), registry);

for (const sphere of SPHERES) {
  console.log(`sphere${sphere.n}: ${bySphere.get(sphere.n).length} deep dive(s)`);
}
console.log(`total: ${files.length} of ${conceptIndex.size} concepts`);
